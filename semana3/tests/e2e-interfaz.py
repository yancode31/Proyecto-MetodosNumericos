"""Prueba de extremo a extremo de la interfaz final: cabecera, inicio, menú, Base de datos (4 pestañas),
Validación y vista móvil. Requiere playwright.  Ejecutar: python tests/e2e-interfaz.py"""
import functools, http.server, json, os, socketserver, sys, tempfile, threading
from playwright.sync_api import sync_playwright

ROOT = os.environ.get('E2E_ROOT') or os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a, **k): pass
httpd = socketserver.TCPServer(('127.0.0.1', 0), functools.partial(Quiet, directory=ROOT)); threading.Thread(target=httpd.serve_forever, daemon=True).start()
URL = f'http://127.0.0.1:{httpd.server_address[1]}/index.html'
fails = []; total = 0
def check(c, m):
    global total; total += 1; print(('  ✔ ' if c else '  ✘ ') + m)
    if not c: fails.append(m)

with sync_playwright() as p:
    b = p.chromium.launch(); ctx = b.new_context(viewport={'width': 1366, 'height': 900}, accept_downloads=True); pg = ctx.new_page()
    errors = []; pg.on('pageerror', lambda e: errors.append(str(e))); pg.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    pg.goto(URL); pg.wait_for_timeout(800)
    nav = lambda name: (pg.locator('.sidebar').get_by_text(name, exact=False).first.click(), pg.wait_for_timeout(500))
    tab = lambda name: (pg.get_by_role('tab', name=name).click(), pg.wait_for_timeout(300))
    overflow = lambda: pg.evaluate('document.documentElement.scrollWidth > window.innerWidth + 1')

    print('\n== Cabecera, inicio y menú')
    top = pg.inner_text('.top-actions')
    check('Modo educativo' in top and 'Base de datos' not in top and 'MN' not in top and pg.locator('.top-actions .avatar, .top-actions button').count() == 0, 'cabecera: solo «Modo educativo» (sin botón Base de datos ni avatar MN)')
    check(pg.locator('.hero-actions button').count() == 1 and 'Iniciar simulación' in pg.inner_text('.hero-actions') and 'Ver la base de datos' not in pg.inner_text('.hero'), 'banner de inicio: un único botón «Iniciar simulación»')
    side = pg.inner_text('.sidebar')
    check(not any(t in side for t in ['Desafío integrador', 'Semana 3 de 3', 'Validación, conclusiones y defensa', 'UMSA', 'Datos sintéticos']), 'menú lateral sin el bloque inferior informativo')
    check(pg.locator('.sidebar nav button, #sideNav button').count() >= 8, 'el menú conserva sus accesos de navegación')

    print('\n== Base de datos')
    nav('Base de datos')
    tabs = pg.eval_on_selector_all('.tabs .tab', 'e => e.map(x => x.innerText.trim())')
    check(tabs == ['Registros', 'Esquema y DER', 'Integridad', 'Respaldo'], f'solo cuatro pestañas: {tabs}')
    check(pg.locator('#regResults .empty-state').count() == 1, 'Registros vacío: invita a cargar demostraciones')
    pg.get_by_role('button', name='Cargar demostraciones').click(); pg.wait_for_timeout(4500)
    stat = pg.inner_text('.reg-stats')
    check('12' in stat.split('\n')[0] and 'Simulaciones guardadas' in stat, 'Registros: total de simulaciones = 12')
    dist = pg.eval_on_selector_all('.dist-row strong', 'e => e.map(x => Number(x.innerText))')
    check(dist == [3, 3, 3, 3, 4, 4, 4], f'distribución por módulo y por escenario: {dist}')
    check(pg.locator('#regResults tbody tr').count() == 10 and 'Página 1 de 2' in pg.inner_text('.pager'), 'tabla de registros paginada (10 por página, 12 en total)')
    check('{' not in pg.inner_text('#regResults') and 'alpha' not in pg.inner_text('#regResults'), 'la tabla no expone parámetros JSON')
    pg.select_option('#regCase', '2'); pg.wait_for_timeout(300)
    check(pg.locator('#regResults tbody tr').count() == 3 and all('Deterioro' in t for t in pg.eval_on_selector_all('#regResults tbody tr td:nth-child(3)', 'e => e.map(x => x.innerText)')), 'filtro por módulo')
    pg.select_option('#regScen', 'ESTRÉS'); pg.wait_for_timeout(300)
    check(pg.locator('#regResults tbody tr').count() == 1, 'filtro combinado módulo + escenario')
    pg.select_option('#regCase', 'TODOS'); pg.select_option('#regScen', 'TODOS'); pg.fill('#regSearch', 'Sensores'); pg.wait_for_timeout(300)
    check(pg.locator('#regResults tbody tr').count() == 3, 'búsqueda por texto'); pg.fill('#regSearch', ''); pg.wait_for_timeout(200)
    pg.locator('#regResults [data-action="open-saved"]').first.click(); pg.wait_for_timeout(800)
    check(pg.locator('#parametersForm').count() == 1 and 'Guardada' in pg.inner_text('.simulation-status'), 'Recuperar abre la simulación guardada con sus parámetros')
    nav('Base de datos'); pg.locator('#regResults [data-action="rerun"]').first.click(); pg.wait_for_timeout(1500)
    check(pg.locator('#parametersForm').count() == 1, 'Relanzar recalcula la simulación')
    nav('Base de datos'); pg.locator('#regResults [data-action="del-sim"]').first.click(); pg.wait_for_timeout(300)
    pg.locator('#modal').get_by_role('button', name='Eliminar').click(); pg.wait_for_timeout(500)
    check('11' in pg.inner_text('.reg-stats').split('\n')[0], 'Eliminar quita el registro (12 → 11)')
    tab('Esquema y DER')
    body = pg.inner_text('.tab-body')
    check(pg.locator('.entity-card').count() == 8 and pg.locator('.der-svg').count() == 1 and pg.locator('pre').count() == 0 and 'CREATE TABLE' not in body and 'SELECT' not in body, 'Esquema y DER: 8 entidades, diagrama visual y sin SQL')
    check('INTEGER' not in body and 'TEXT' not in body and 'REAL' not in body, 'el DER no expone tipos SQL')
    tab('Integridad'); check(pg.locator('.integrity-card').count() == 4, 'Integridad: cuatro comprobaciones')
    pg.get_by_role('button', name='Cerrar y reabrir la base').click(); pg.wait_for_timeout(1500)
    check('Confirmado' in pg.inner_text('.integrity-grid'), 'Integridad: recuperación confirmada tras cerrar y reabrir')
    pg.get_by_role('button', name='Verificar registros').click(); pg.wait_for_timeout(4000)
    txt = pg.inner_text('.integrity-grid')
    check('Reproducibilidad confirmada' in txt and '11 de 11' in txt, 'Integridad: los 11 registros se reproducen dentro de la tolerancia')
    check('Correcto' in txt and 'coherente' in txt, 'Integridad: información coherente')
    tab('Respaldo'); check(pg.locator('.backup-card').count() == 4 and 'JSON' in pg.inner_text('.backup-grid') and 'CSV' in pg.inner_text('.backup-grid'), 'Respaldo: exportar JSON/CSV, importar y cargar demostraciones')
    with pg.expect_download() as d: pg.get_by_role('button', name='Descargar JSON').click()
    jpath = os.path.join(tempfile.mkdtemp(), 'respaldo.json'); d.value.save_as(jpath); data = json.load(open(jpath, encoding='utf-8'))
    check(isinstance(data, dict) and len(json.dumps(data)) > 1000, 'se descarga un respaldo JSON con datos')
    with pg.expect_download() as d: pg.get_by_role('button', name='Descargar CSV').click()
    cpath = os.path.join(tempfile.mkdtemp(), 'r.csv'); d.value.save_as(cpath); lines = open(cpath, encoding='utf-8-sig').read().strip().split('\n')
    check(len(lines) == 12 and lines[0].startswith('"N.º"'), f'el CSV tiene encabezado y 11 registros ({len(lines)} líneas)')
    pg.get_by_role('button', name='Reiniciar la base').click(); pg.wait_for_timeout(300); pg.locator('#modal').get_by_role('button', name='Reiniciar').click(); pg.wait_for_timeout(800)
    tab('Registros'); check('0' in pg.inner_text('.reg-stats').split('\n')[0] and pg.locator('#regResults .empty-state').count() == 1, 'tras reiniciar, no quedan registros')
    tab('Respaldo'); pg.set_input_files('#importFile', jpath); pg.wait_for_timeout(1500); tab('Registros')
    check('11' in pg.inner_text('.reg-stats').split('\n')[0], 'importar el JSON restaura los 11 registros')

    print('\n== Validación')
    nav('Validación')
    check(pg.locator('ol.pipeline').count() == 0 and 'Ejecutar prueba' not in pg.inner_text('main'), 'sin la lista de 6 pasos técnicos')
    check(pg.locator('#pipeCase').count() == 1 and pg.locator('#pipeScenario').count() == 1 and pg.get_by_role('button', name='Validar', exact=True).count() == 1, 'selector de módulo y escenario + botón Validar')
    pg.select_option('#pipeCase', '3'); pg.select_option('#pipeScenario', 'ESTRÉS'); pg.get_by_role('button', name='Validar', exact=True).click(); pg.wait_for_timeout(3000)
    v = pg.inner_text('main')
    check(all(t in v for t in ['Validación correcta', 'Resultados consistentes', 'Diferencias dentro de la tolerancia', 'Reproducibilidad confirmada']), 'mensajes claros de validación correcta')
    check(pg.locator('.status-banner.ok').count() == 1 and pg.locator('.table-card tbody tr').count() >= 6 and 'Coincide' in v, 'resumen y tabla con coincidencias, tolerancia y estado')
    check(pg.input_value('#pipeCase') == '3' and pg.input_value('#pipeScenario') == 'ESTRÉS', 'se conserva la selección de módulo y escenario')
    pg.get_by_role('button', name='Validar métodos').click(); pg.wait_for_timeout(1500)
    v = pg.inner_text('main'); check('verificaciones coinciden con su valor de referencia' in v and pg.locator('.val-details').count() == 1 and not pg.locator('.val-details').get_attribute('open'), 'exactitud frente a referencias, con detalle plegado')

    print('\n== Vista móvil (390 px)')
    for name, path in [('Panel general', None), ('Base de datos', None), ('Validación', None)]:
        pg.set_viewport_size({'width': 1366, 'height': 900}); nav(name); pg.set_viewport_size({'width': 390, 'height': 800}); pg.wait_for_timeout(300)
        check(not overflow(), f'{name}: sin desbordamiento horizontal')
    pg.set_viewport_size({'width': 1366, 'height': 900})
    check(not errors, f'sin errores de consola ni excepciones {errors[:2]}')
    b.close(); httpd.shutdown()
print(f'\n{"OK" if not fails else "FALLÓ"} · {total - len(fails)}/{total} comprobaciones de interfaz'); sys.exit(1 if fails else 0)
